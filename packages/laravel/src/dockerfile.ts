import type { LaravelProject } from './project';

const PREBUILT_PHP_IMAGES: Partial<Record<string, string>> = {
  '8.5':
    'ghcr.io/jacobparis/vercel-laravel-php@sha256:19a6a8aa691d853b0393ca740a9297becd642ab1f9a9cffe3b2aa6221c63a867',
};

function packageManagerCommands(project: LaravelProject): {
  install: string;
  build: string;
} {
  const corepack = project.packageManagerVersion
    ? `corepack enable ${project.packageManager} && corepack install --global ${project.packageManager}@${project.packageManagerVersion}`
    : `corepack enable ${project.packageManager}`;

  switch (project.packageManager) {
    case 'pnpm':
      return {
        install: `${corepack} && pnpm install --frozen-lockfile`,
        build: 'pnpm run build',
      };
    case 'yarn':
      return {
        install: `${corepack} && yarn install --frozen-lockfile`,
        build: 'yarn build',
      };
    case 'bun':
      return {
        install: 'npm install --global bun && bun install --frozen-lockfile',
        build: 'bun run build',
      };
    default:
      return {
        install: project.packageLock ? 'npm ci' : 'npm install',
        build: 'npm run build',
      };
  }
}

function extensionInstall(
  project: LaravelProject,
  includeDefaultExtensions: boolean
): string[] {
  const apt = new Set<string>();
  const configure: string[] = [];
  // The official Apache image already ships Laravel's required curl, DOM,
  // mbstring, PDO SQLite, SimpleXML, XML, and OPcache modules. Rebuilding them
  // is both slow and, on PHP 8.5, breaks DOM because its bundled Lexbor headers
  // are not part of the image's extension source tree.
  const install = new Set<string>();
  const pecl: string[] = [];

  if (includeDefaultExtensions) {
    apt.add('libicu-dev');
    apt.add('libpq-dev');
    apt.add('libzip-dev');
    apt.add('unzip');
    install.add('bcmath');
    install.add('intl');
    install.add('pcntl');
    install.add('pdo_mysql');
    install.add('pdo_pgsql');
    install.add('sockets');
    install.add('zip');
  }

  if (project.extensions.has('gd')) {
    apt.add('libfreetype6-dev');
    apt.add('libjpeg62-turbo-dev');
    apt.add('libpng-dev');
    configure.push('docker-php-ext-configure gd --with-freetype --with-jpeg');
    install.add('gd');
  }
  if (project.extensions.has('soap')) {
    apt.add('libxml2-dev');
    install.add('soap');
  }
  if (project.extensions.has('exif')) {
    install.add('exif');
  }
  if (project.extensions.has('imagick')) {
    apt.add('libmagickwand-dev');
    pecl.push('imagick');
  }
  if (project.extensions.has('redis')) {
    pecl.push('redis');
  }

  return [
    ...(apt.size
      ? [
          `RUN apt-get update && apt-get install -y --no-install-recommends ${[
            ...apt,
          ].join(' ')} \\`,
          '    && rm -rf /var/lib/apt/lists/*',
        ]
      : []),
    ...configure.map(command => `RUN ${command}`),
    ...(install.size
      ? [`RUN docker-php-ext-install -j"$(nproc)" ${[...install].join(' ')}`]
      : []),
    ...(pecl.length
      ? [
          `RUN pecl install ${pecl.join(' ')} \\`,
          `    && docker-php-ext-enable ${pecl.join(' ')}`,
        ]
      : []),
  ];
}

function buildEnvArgs(buildEnv: Record<string, string | undefined>): string[] {
  return Object.keys(buildEnv)
    .filter(key => /^VITE_[A-Z0-9_]+$/.test(key))
    .sort()
    .map(key => `ARG ${key}`);
}

export function generateDockerfile(
  project: LaravelProject,
  buildEnv: Record<string, string | undefined> = {}
): string {
  const assets = packageManagerCommands(project);
  const packageFiles = [
    'package.json',
    project.packageLock,
    ...(project.packageConfigFiles ?? []),
  ].filter(Boolean);
  const composerFiles = [
    'composer.json',
    project.composerLock ? 'composer.lock' : undefined,
  ].filter(Boolean);
  const prebuiltPhpImage = PREBUILT_PHP_IMAGES[project.phpVersion];

  return [
    '# syntax=docker/dockerfile:1.7',
    '# Generated by @vercel/laravel. This file is not written to the project.',
    `FROM ${
      prebuiltPhpImage ?? `php:${project.phpVersion}-apache-bookworm`
    } AS php-base`,
    ...extensionInstall(project, prebuiltPhpImage === undefined),
    'RUN a2enmod expires headers rewrite \\',
    `    && printf '%s\\n' 'SetEnvIf X-Forwarded-Proto "^https$" HTTPS=on' > /etc/apache2/conf-available/vercel-proxy.conf \\`,
    '    && a2enconf vercel-proxy \\',
    "    && sed -ri -e 's!/var/www/html!/var/www/html/public!g' /etc/apache2/sites-available/*.conf \\",
    "    && sed -ri -e 's!/var/www/!/var/www/html/public!g' /etc/apache2/apache2.conf /etc/apache2/conf-available/*.conf",
    'WORKDIR /var/www/html',
    '',
    'FROM node:24-bookworm-slim AS node',
    'FROM composer:2 AS composer',
    '',
    'FROM php-base AS build',
    'COPY --from=node /usr/local/ /usr/local/',
    'COPY --from=composer /usr/bin/composer /usr/local/bin/composer',
    'WORKDIR /app',
    'ARG COMPOSER_AUTH',
    ...buildEnvArgs(buildEnv),
    `COPY ${composerFiles.join(' ')} ./`,
    'RUN composer install --no-dev --no-interaction --no-progress --prefer-dist --no-scripts',
    ...(project.packageManager
      ? [`COPY ${packageFiles.join(' ')} ./`, `RUN ${assets.install}`]
      : []),
    'COPY . .',
    'RUN composer install --no-dev --no-interaction --no-progress --prefer-dist --optimize-autoloader \\',
    '    && php artisan package:discover --ansi',
    ...(project.hasWayfinder
      ? ['RUN php -d memory_limit=512M artisan wayfinder:generate --ansi']
      : []),
    ...(project.hasAssetBuild ? [`RUN ${assets.build}`] : []),
    '',
    'FROM php-base AS runtime',
    'ENV APP_ENV=production \\',
    '    APP_DEBUG=false \\',
    '    LOG_CHANNEL=stderr \\',
    '    SESSION_DRIVER=cookie \\',
    '    CACHE_STORE=array \\',
    '    FILESYSTEM_DISK=vercel \\',
    '    QUEUE_CONNECTION=vercel',
    'COPY --from=build --chown=www-data:www-data /app /var/www/html',
    'RUN rm -f /var/www/html/.env \\',
    '    && mkdir -p storage/framework/cache storage/framework/sessions storage/framework/views storage/logs bootstrap/cache \\',
    '    && cp -R /opt/vercel/laravel /var/www/html/.vercel-runtime \\',
    "    && sed -i 's!/opt/vercel/laravel!/var/www/html/.vercel-runtime!g' /usr/local/etc/php/conf.d/vercel-laravel.ini /var/www/html/.vercel-runtime/runtime/autoload.php \\",
    '    && php /var/www/html/.vercel-runtime/runtime/install.php /var/www/html \\',
    '    && chown -R www-data:www-data storage bootstrap/cache /var/www/html/.vercel-runtime',
    'EXPOSE 80',
    'CMD ["apache2-foreground"]',
    '',
  ].join('\n');
}
