import { mkdtemp, mkdir, writeFile, rm, realpath } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { describe, expect, it } from 'vitest';
import type { BuildResultV2Typical, NodejsLambda } from '@vercel/build-utils';
import { build } from '../src/index';

const meta = { skipDownload: true };

/**
 * Projects where the entrypoint only exists after the Build Command runs
 * (e.g. `package.json#main` pointing into `dist/` produced by `tsc`).
 * Wrapper builders resolve the entrypoint after install + build; the
 * backends builder must do the same.
 */
describe.skipIf(process.platform === 'win32')(
  'entrypoint detection after build command',
  () => {
    it('finds an entrypoint generated by the build command', async () => {
      const repoRoot = await realpath(
        await mkdtemp(join(tmpdir(), 'backends-post-build-'))
      );
      const workDir = join(repoRoot, 'app');
      await mkdir(join(workDir, 'src'), { recursive: true });

      // `main` points at a file that does not exist until the build
      // command runs; the source file uses a non-well-known name so
      // filename heuristics cannot find it pre-build.
      await writeFile(
        join(workDir, 'package.json'),
        JSON.stringify({
          name: 'post-build-app',
          version: '1.0.0',
          type: 'module',
          main: 'dist/index.js',
          dependencies: { hono: '4.10.0' },
        })
      );
      await writeFile(
        join(workDir, 'src/server-entry.js'),
        [
          "import { Hono } from 'hono';",
          'const app = new Hono();',
          "app.get('/', c => c.text('ok'));",
          'export default app;',
        ].join('\n')
      );

      // Minimal hono package so rolldown can resolve the import.
      const honoDir = join(workDir, 'node_modules/hono');
      await mkdir(honoDir, { recursive: true });
      await writeFile(
        join(honoDir, 'package.json'),
        JSON.stringify({
          name: 'hono',
          version: '4.10.0',
          type: 'module',
          main: 'index.js',
        })
      );
      await writeFile(
        join(honoDir, 'index.js'),
        'export class Hono { get() {} }\n'
      );

      try {
        const result = (await build({
          files: {},
          workPath: workDir,
          config: {
            zeroConfig: true,
            projectSettings: {
              installCommand: 'true',
              buildCommand:
                'mkdir -p dist && cp src/server-entry.js dist/index.js',
            },
          },
          meta,
          entrypoint: 'package.json',
          repoRootPath: repoRoot,
        })) as BuildResultV2Typical;

        const lambda = result.output.index as unknown as NodejsLambda;
        expect(lambda).toBeDefined();
        expect(lambda.handler).toBeTruthy();
      } finally {
        await rm(repoRoot, { recursive: true, force: true });
      }
    }, 30000);
  }
);
